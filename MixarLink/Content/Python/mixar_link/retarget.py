"""Mannequin clips on Mixar characters.

A package's manifest maps a humanoid rig's bones onto the UE5 Mannequin's
(``engine.skeletons[].bones``: Mannequin bone -> this rig's bone). From it:

- ``IK_Mannequin`` (shared, under ``/Game/Mixar/Retarget``): an IK Rig on the
  project's Mannequin, its retarget chains auto-generated by Unreal;
- ``IK_<character>``: the character's IK Rig, every Mannequin chain whose
  start and end bones the map names, under the same chain name;
- ``RTG_Mannequin_To_<character>``: the IK Retargeter between them.

``retarget_clips`` then duplicates Mannequin animations onto the character
(``<clip>_<character>`` in the package's ``Anims`` folder). Nothing outside
``/Game/Mixar`` is written; the Mannequin assets are only read.
"""

import unreal

from . import MIXAR_FOLDER

RETARGET_FOLDER = f"{MIXAR_FOLDER}/Retarget"
# The Mannequins the engine's templates ship (the first one present is used).
MANNEQUIN_MESHES = ("/Game/Characters/Mannequins/Meshes/SKM_Manny_Simple",
                    "/Game/Characters/Mannequins/Meshes/SKM_Manny",
                    "/Game/Characters/Mannequins/Meshes/SKM_Quinn_Simple",
                    "/Game/Characters/Mannequins/Meshes/SKM_Quinn")


def _assets():
    return unreal.AssetToolsHelpers.get_asset_tools()


def _load_or_create(path: str, cls, factory):
    if unreal.EditorAssetLibrary.does_asset_exist(path):
        return unreal.EditorAssetLibrary.load_asset(path)
    folder, name = path.rsplit("/", 1)
    return _assets().create_asset(name, folder, cls, factory)


def mannequin():
    """The project's UE5 Mannequin skeletal mesh, or None."""
    for path in MANNEQUIN_MESHES:
        if unreal.EditorAssetLibrary.does_asset_exist(path):
            return unreal.EditorAssetLibrary.load_asset(path)
    return None


def _source_rig(manny):
    rig = _load_or_create(f"{RETARGET_FOLDER}/IK_Mannequin", unreal.IKRigDefinition, unreal.IKRigDefinitionFactory())
    ctrl = unreal.IKRigController.get_controller(rig)
    if not ctrl.get_retarget_chains():
        ctrl.set_skeletal_mesh(manny)
        ctrl.apply_auto_generated_retarget_definition()
    return rig, ctrl


def prepare(target, bones: dict, folder: str, name: str) -> dict:
    """The IK rigs and retargeter for ``target`` (a SkeletalMesh) from its
    bone map. Returns {"retargeter", "chains", "skipped"} or {"error"}."""
    manny = mannequin()
    if manny is None:
        return {"error": "The project has no UE5 Mannequin (/Game/Characters/Mannequins), so there are "
                         "no Mannequin clips to retarget; animate the character in Mixar instead."}
    src_rig, src = _source_rig(manny)
    tgt_rig = _load_or_create(f"{folder}/IK_{name}", unreal.IKRigDefinition, unreal.IKRigDefinitionFactory())
    tgt = unreal.IKRigController.get_controller(tgt_rig)
    tgt.set_skeletal_mesh(target)
    for chain in list(tgt.get_retarget_chains()):
        tgt.remove_retarget_chain(chain.chain_name)
    root = {k.lower(): v for k, v in bones.items()}.get("pelvis")
    if root:
        tgt.set_retarget_root(root)
    chains, skipped = [], []
    # Unreal names compare without case, and one spells a name the way it was
    # first registered (the Mannequin's "head" can read "Head"): match the same way.
    folded = {k.lower(): v for k, v in bones.items()}
    for chain in src.get_retarget_chains():
        chain_name = str(chain.chain_name)
        start = folded.get(str(src.get_retarget_chain_start_bone(chain.chain_name)).lower())
        end = folded.get(str(src.get_retarget_chain_end_bone(chain.chain_name)).lower())
        if start and end:
            tgt.add_retarget_chain(chain_name, start, end, "")
            chains.append(chain_name)
        else:
            unmapped = [str(b) for b in (src.get_retarget_chain_start_bone(chain.chain_name),
                                         src.get_retarget_chain_end_bone(chain.chain_name))
                        if str(b).lower() not in folded]
            skipped.append(f"{chain_name} (no {', '.join(dict.fromkeys(unmapped))})")
    rtg = _load_or_create(f"{folder}/RTG_Mannequin_To_{name}", unreal.IKRetargeter, unreal.IKRetargetFactory())
    rc = unreal.IKRetargeterController.get_controller(rtg)
    rc.set_ik_rig(unreal.RetargetSourceOrTarget.SOURCE, src_rig)
    rc.set_ik_rig(unreal.RetargetSourceOrTarget.TARGET, tgt_rig)
    if rc.get_num_retarget_ops() == 0:
        rc.add_default_ops()
    rc.assign_ik_rig_to_all_ops(unreal.RetargetSourceOrTarget.SOURCE, src_rig)
    rc.assign_ik_rig_to_all_ops(unreal.RetargetSourceOrTarget.TARGET, tgt_rig)
    rc.auto_map_chains(unreal.AutoMapChainType.EXACT, True)
    rc.auto_align_all_bones(unreal.RetargetSourceOrTarget.TARGET)
    unreal.EditorAssetLibrary.save_directory(RETARGET_FOLDER)
    unreal.EditorAssetLibrary.save_directory(folder)
    return {"retargeter": rtg.get_path_name().split(".", 1)[0], "chains": chains, "skipped": skipped}


def mannequin_clips(limit: int = 60) -> list:
    """Animation sequences on the Mannequin's skeleton, by asset path."""
    manny = mannequin()
    if manny is None:
        return []
    skeleton = manny.get_editor_property("skeleton")
    registry = unreal.AssetRegistryHelpers.get_asset_registry()
    found = []
    for data in registry.get_assets_by_class(unreal.TopLevelAssetPath("/Script/Engine", "AnimSequence")):
        path = str(data.package_name)
        if not path.startswith("/Game/") or path.startswith(MIXAR_FOLDER + "/"):
            continue
        anim = unreal.EditorAssetLibrary.load_asset(path)
        if anim and anim.get_skeleton() == skeleton:
            found.append(path)
        if len(found) >= limit:
            break
    return sorted(found)


def retarget_clips(target, retargeter: str, clips: list, folder: str, name: str) -> list:
    """Each Mannequin clip duplicated onto ``target``; returns their paths."""
    manny = mannequin()
    rtg = unreal.EditorAssetLibrary.load_asset(retargeter)
    if manny is None or rtg is None:
        return []
    anims = f"{folder}/Anims"
    wanted = [unreal.EditorAssetLibrary.find_asset_data(c) for c in clips]
    inputs = unreal.IKRetargetBatchOperationInputs()
    inputs.set_editor_property("assets_to_retarget", [w for w in wanted if w.is_valid()])
    inputs.set_editor_property("source_mesh", manny)
    inputs.set_editor_property("target_mesh", target)
    inputs.set_editor_property("ik_retarget_asset", rtg)
    inputs.set_editor_property("suffix", f"_{name}")
    inputs.set_editor_property("target_path", anims)
    inputs.set_editor_property("include_referenced_assets", False)
    inputs.set_editor_property("overwrite_existing_files", True)
    created = unreal.IKRetargetBatchOperation.run_batch_retarget(inputs)
    unreal.EditorAssetLibrary.save_directory(anims)
    return [str(a.package_name) for a in created]


def retargeted_path(clip: str, folder: str, name: str) -> str:
    return f"{folder}/Anims/{clip.rsplit('/', 1)[-1]}_{name}"
